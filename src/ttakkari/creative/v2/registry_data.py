def _skill(
    sid: str,
    name: str,
    area: str,
    claims: list[Claim],
    depends: list[str],
    validation: list[str],
    notes: str = "",
) -> RegistryEntry:
    return RegistryEntry(
        id=f"skill.{sid}",
        kind="skill",
        name=name,
        claims=claims,
        probes=[f"skill:{sid}"],
        depends_on=depends,
        integration="lab_only",
        entry_point=f"{area}/skills-draft/{sid}",
        validation=validation,
        notes=notes or "lab 초안(미설치): 제작 런타임에 등록되지 않았다.",
    )


